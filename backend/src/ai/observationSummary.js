'use strict';
const llm = require('./llm');

/**
 * AI-assisted organisation of care observations (non-diagnostic).
 *
 * Always returns a deterministic digest (counts by category, self-reported
 * mood distribution, notes in date order). If an LLM is configured, it also
 * drafts a short narrative that MUST cite note ids; the draft is discarded if
 * it cites unknown notes or uses diagnostic/clinical-judgement language.
 * The output is labelled as a draft to be checked against the original notes.
 */
const DIAGNOSTIC_RE = /\b(diagnos\w*|depress\w*|dementia stage|stage \d|declin\w*|deteriorat\w*|progress\w* of (the )?disease|psychosis|delirium|prescrib\w*|should (start|stop|increase|reduce))\b/i;

function digest(notes, moods, days) {
  const byCategory = {};
  for (const n of notes) byCategory[n.category || 'general'] = (byCategory[n.category || 'general'] || 0) + 1;
  const moodCounts = {};
  for (const m of moods) moodCounts[m.mood] = (moodCounts[m.mood] || 0) + 1;
  return {
    periodDays: days,
    observationCount: notes.length,
    byCategory,
    selfReportedMoodCounts: moodCounts,
    notes: notes.map((n, i) => ({ ref: `N${i + 1}`, id: n.id, date: n.createdAt, category: n.category, authorCaregiverId: n.caregiverId }))
  };
}

async function summarize(notes, moods, { days = 14 } = {}) {
  const base = digest(notes, moods, days);
  const result = { digest: base, narrative: null, narrativeStatus: llm.available() ? null : 'no_llm_configured', label: 'Draft summary generated by software. Check it against the original notes. Not a clinical assessment.' };
  if (!llm.available() || notes.length === 0) {
    if (notes.length === 0) result.narrativeStatus = 'no_observations';
    return result;
  }
  const lines = notes.map((n, i) => `[N${i + 1}] ${new Date(n.createdAt).toISOString().slice(0, 10)} (${n.category || 'general'}): ${String(n.note).slice(0, 500)}`);
  const out = await llm.complete([
    { role: 'system', content: 'You organise caregiver observations for a care team. Summarise ONLY what the notes say, grouped by theme, in at most 5 short bullet points. Cite note ids like [N2] for every point. Do not diagnose, interpret clinically, predict, or recommend treatment. Respond with JSON {"bullets": [string]}.' },
    { role: 'user', content: lines.join('\n') }
  ], { json: true, maxTokens: 400, temperature: 0.2 });
  if (!out) { result.narrativeStatus = 'llm_unavailable'; return result; }
  let bullets = [];
  try { bullets = JSON.parse(String(out.content).match(/\{[\s\S]*\}/)[0]).bullets || []; } catch { bullets = []; }
  const valid = new Set(notes.map((_, i) => `N${i + 1}`));
  const ok = bullets.length > 0 && bullets.every(b => {
    const refs = String(b).match(/N\d+/g) || [];
    return refs.length > 0 && refs.every(r => valid.has(r)) && !DIAGNOSTIC_RE.test(b);
  });
  if (!ok) { result.narrativeStatus = 'rejected_by_checks'; return result; }
  result.narrative = bullets.map(String);
  result.narrativeStatus = 'ok';
  result.model = out.model;
  return result;
}

module.exports = { summarize, digest, DIAGNOSTIC_RE };
